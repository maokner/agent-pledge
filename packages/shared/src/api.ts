import { z } from "zod";
import { AgentLogLevel, IsoTime, PIN_REGEX, TaskStatus } from "./domain";
import { Money } from "./money";
import { AgentLogEntry, ClaimView, MediaView, SubtaskView, TaskView } from "./views";

/**
 * HTTP request and response schemas. See docs/api.md for auth and error codes.
 * Every error response has the shape ApiError.
 */

export const ApiError = z.object({
  error: z.string(), // machine code, e.g. "already_claimed"
  message: z.string(), // human text
  details: z.unknown().optional(),
});
export type ApiError = z.infer<typeof ApiError>;

/** Error codes used across endpoints. */
export const ErrorCode = {
  badRequest: "bad_request", // 400
  unauthorized: "unauthorized", // 401
  notFound: "not_found", // 404
  alreadyClaimed: "already_claimed", // 409
  conflict: "conflict", // 409 (wrong state)
  expired: "expired", // 410 (deadline passed or failed)
  wrongPin: "wrong_pin", // 422
  pinLocked: "pin_locked", // 423
  notSeatHold: "not_seat_hold", // 422 (create_task only)
  ledgerError: "ledger_error", // 502
  notImplemented: "not_implemented", // 501
} as const;

const PriceInput = z.union([z.number().positive(), z.string().min(1)]);

// ---------- Voice agent tools (header x-agent-pledge-secret) ----------

/** POST /tools/create_task */
export const CreateTaskRequest = z.object({
  description: z.string().min(1).max(500),
  place: z.string().min(1).max(200),
  time_limit_minutes: z.coerce.number().int().min(1).max(240),
  /** Number or string from ElevenLabs ("5", 5, "5.00", "$5"). The server normalizes it to Money. */
  price_usd: PriceInput,
  caller_phone: z.string().max(40).nullish(),
  /**
   * The ElevenLabs conversation id. A retry of the same tool call (same call_id) returns the
   * first call's task and PIN instead of making a second task. Empty or absent: no dedupe.
   */
  call_id: z.string().max(128).nullish(),
});
export type CreateTaskRequest = z.infer<typeof CreateTaskRequest>;

export const CreateTaskResponse = z.object({
  task_id: z.string(),
  /** The 4-digit PIN. Returned only here, once. The voice agent reads it to the caller. */
  pin: z.string(),
  board_url: z.string(),
  status: TaskStatus,
  price: Money,
  deadline: IsoTime,
});
export type CreateTaskResponse = z.infer<typeof CreateTaskResponse>;

/** GET /tools/task_status/:taskId */
export const TaskStatusResponse = z.object({
  task_id: z.string(),
  status: TaskStatus,
  helper_note: z.string().nullable(),
  deadline: IsoTime,
  price: Money,
});
export type TaskStatusResponse = z.infer<typeof TaskStatusResponse>;

// ---------- Local agent (Authorization: Bearer AGENT_TOKEN) ----------

/** POST /agent/tasks/:id/claim */
export const ClaimTaskRequest = z.object({
  /** Hash of the agent's own NFTokenAcceptOffer. Optional only when LEDGER_MODE=fake. */
  tx_hash: z.string().optional(),
});
export type ClaimTaskRequest = z.infer<typeof ClaimTaskRequest>;
export const ClaimTaskResponse = z.object({ task: TaskView });
export type ClaimTaskResponse = z.infer<typeof ClaimTaskResponse>;

/** POST /agent/tasks/:id/subtasks */
export const CreateSubtaskRequest = z.object({
  price: Money,
  /**
   * Client-generated sub-task ID (newId("sub")). Required when funding_tx_hash is given,
   * because the agent's funding Payment carries it as the memo. Generated by the server otherwise.
   */
  subtask_id: z
    .string()
    .regex(/^sub_[0-9a-z]{16}$/)
    .optional(),
  /** Hash of the agent's own Payment agent -> vault. Optional only when LEDGER_MODE=fake. */
  funding_tx_hash: z.string().optional(),
  /** Defaults to the parent task deadline. */
  deadline: IsoTime.optional(),
});
export type CreateSubtaskRequest = z.infer<typeof CreateSubtaskRequest>;
export const CreateSubtaskResponse = z.object({
  subtask: SubtaskView,
  claim_url: z.string(),
  claim_code: z.string(),
});
export type CreateSubtaskResponse = z.infer<typeof CreateSubtaskResponse>;

/** GET /agent/tasks/:id -> TaskView */
export const GetTaskResponse = TaskView;
export type GetTaskResponse = TaskView;

/** POST /agent/tasks/:id/redeem */
export const RedeemTaskRequest = z.object({
  /** The agent's sell offer (NFT -> vault for price + pledge). Optional only when LEDGER_MODE=fake. */
  offer_id: z.string().optional(),
  tx_hash: z.string().optional(),
});
export type RedeemTaskRequest = z.infer<typeof RedeemTaskRequest>;
export const RedeemTaskResponse = z.object({
  task: TaskView,
  amount: Money,
  payout_tx_hash: z.string(),
  explorer_url: z.string(),
});
export type RedeemTaskResponse = z.infer<typeof RedeemTaskResponse>;

/**
 * POST /agent/subtasks/:id/screenshot — multipart/form-data:
 *   file: image (png/jpeg/webp), required
 *   post_text: string, required
 *   posted_at: ISO time, optional (defaults to now)
 */
export const ScreenshotFields = z.object({
  post_text: z.string().min(1).max(1000),
  posted_at: IsoTime.optional(),
});
export type ScreenshotFields = z.infer<typeof ScreenshotFields>;
export const ScreenshotResponse = z.object({ media: MediaView, subtask: SubtaskView });
export type ScreenshotResponse = z.infer<typeof ScreenshotResponse>;

/** POST /agent/log */
export const AgentLogRequest = z.object({
  message: z.string().min(1).max(2000),
  task_id: z.string().nullish(),
  subtask_id: z.string().nullish(),
  level: AgentLogLevel.default("info"),
});
export type AgentLogRequest = z.infer<typeof AgentLogRequest>;
export const AgentLogResponse = z.object({ entry: AgentLogEntry });
export type AgentLogResponse = z.infer<typeof AgentLogResponse>;

// ---------- Claim page (helper token: cookie or header) ----------

/** GET /claim/:code -> ClaimView */
export const GetClaimResponse = ClaimView;

/** POST /claim/:code/claim (no body) */
export const ClaimSubtaskResponse = z.object({
  /** Also set as a signed cookie. Send it back as `Authorization: Bearer <token>` or `x-helper-token`. */
  helper_token: z.string(),
  claim: ClaimView,
});
export type ClaimSubtaskResponse = z.infer<typeof ClaimSubtaskResponse>;

/**
 * POST /claim/:code/photo — multipart/form-data:
 *   file: image, optional (a note alone is fine)
 *   note: string, optional (max 280)
 * At least one of the two is required.
 */
export const PhotoFields = z.object({ note: z.string().max(280).optional() });
export type PhotoFields = z.infer<typeof PhotoFields>;
export const PhotoResponse = z.object({ claim: ClaimView, media: MediaView.nullable() });
export type PhotoResponse = z.infer<typeof PhotoResponse>;

/** POST /claim/:code/pin */
export const PinRequest = z.object({ pin: z.string().regex(PIN_REGEX) });
export type PinRequest = z.infer<typeof PinRequest>;
/** 200 on the correct PIN (also on a repeat after success: idempotent). */
export const PinResponse = z.object({
  claim: ClaimView,
  payout: z.object({ amount: Money, tx_hash: z.string(), explorer_url: z.string() }),
});
export type PinResponse = z.infer<typeof PinResponse>;
/** 422 wrong_pin details / 423 pin_locked details. */
export const PinErrorDetails = z.object({
  attempts: z.number().int(),
  attempts_left: z.number().int(),
});
export type PinErrorDetails = z.infer<typeof PinErrorDetails>;

// ---------- Admin (Authorization: Bearer AGENT_TOKEN) ----------

/** POST /admin/tasks/:id/fail */
export const AdminFailRequest = z.object({ reason: z.string().max(200).optional() });
export type AdminFailRequest = z.infer<typeof AdminFailRequest>;
export const AdminFailResponse = z.object({ task: TaskView });
export type AdminFailResponse = z.infer<typeof AdminFailResponse>;

// ---------- Health ----------

export const HealthResponse = z.object({
  ok: z.literal(true),
  ledger_mode: z.enum(["fake", "xrpl"]),
  time: IsoTime,
});
export type HealthResponse = z.infer<typeof HealthResponse>;
